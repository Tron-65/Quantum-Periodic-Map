export function getChemicalBehaviorAr(el: ChemicalElement): string {
  if (FEATURED_BEHAVIOR_AR[el.z]) {
    return FEATURED_BEHAVIOR_AR[el.z];
  }

  const nameAr = ELEMENT_NAMES_AR[el.z] ?? el.name;
  const oxList = el.oxidationStates
    .map((s) => (s > 0 ? `+${s}` : `${s}`))
    .join('، ');

  if (el.family === 'noble-gas') {
    return `غلاف التكافؤ المغلق (${el.differentiatingConfig}) في ${nameAr} يمنح استقراراً إلكترونياً عالياً وخمولاً كيميائياً في الظروف القياسية (حالات الأكسدة: ${oxList}).`;
  }
  if (el.block === 's') {
    return `إلكترونات التكافؤ الخارجية في ${el.differentiatingConfig} تتحرك بعيداً عن النواة الداخلية، ما يمنح ${nameAr} طابعاً فلزياً قوياً وميلاً لفقد الإلكترونات نحو حالة الأكسدة ${oxList}.`;
  }
  if (el.block === 'f') {
    return `تُضاف الإلكترونات تدريجياً إلى الغلاف الداخلي العميق ${el.differentiatingOrbital} (${el.differentiatingConfig}) بينما تتحكم إلكترونات التكافؤ الخارجية في السلوك الكيميائي المستقر (${oxList}) والخصائص المغناطيسية.`;
  }
  if (el.block === 'd') {
    return `تشارك مدارات ${el.differentiatingOrbital} (${el.differentiatingConfig}) مع إلكترونات s الخارجية لتوفير مرونة في حالات الأكسدة (${oxList}) وترابط فلزي وتحفيزي متميز.`;
  }
  if (el.metallicCharacter >= 55) {
    return `يقع ${nameAr} في فئة ${el.differentiatingOrbital} (${el.differentiatingConfig}) مع تأثير حجب من المدارات الداخلية يجعل سلوكه فلزياً واضحاً في حالات الأكسدة ${oxList}.`;
  }
  return `تحدد بنية التكافؤ ${el.valenceStructure} (المدار المميّز ${el.differentiatingConfig}) روابط ${nameAr} الاتجاهية وميله الكيميائي عبر حالات الأكسدة ${oxList}.`;
}

export function getAnomalyNoteAr(el: ChemicalElement): string | undefined {
  if (!el.anomalyNote) return undefined;
  return `استثناء في مبدأ أوفباو: التوزيع الأرضي (${el.condensedConfig}) مفضّل طاقياً بسبب استقرار التبادل المغزلي أو امتلاء تحت-الغلاف أو التأثيرات النسبية.`;
}
